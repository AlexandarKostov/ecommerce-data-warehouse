CREATE DATABASE IF NOT EXISTS ecommerce_dw;

USE ecommerce_dw;

-- ============================================================
-- 1. ETL AUDIT TABLE
-- Tracks every pipeline execution
-- ============================================================

CREATE TABLE IF NOT EXISTS etl_pipeline_runs (
    run_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    pipeline_name VARCHAR(100) NOT NULL,
    started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at DATETIME NULL,
    status ENUM('RUNNING', 'SUCCESS', 'FAILED') NOT NULL DEFAULT 'RUNNING',
    records_extracted BIGINT NOT NULL DEFAULT 0,
    records_loaded BIGINT NOT NULL DEFAULT 0,
    records_rejected BIGINT NOT NULL DEFAULT 0,
    error_message TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;


-- ============================================================
-- 2. STAGING LAYER
-- Raw source data is initially stored as text.
-- This allows us to validate and reject bad values in Python.
-- ============================================================

CREATE TABLE IF NOT EXISTS stg_customers (
    staging_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    etl_run_id BIGINT NULL,
    source_customer_id VARCHAR(100),
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(100),
    country VARCHAR(100),
    city VARCHAR(100),
    registration_date VARCHAR(100),
    source_file VARCHAR(255),
    loaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stg_customers_run
        FOREIGN KEY (etl_run_id)
        REFERENCES etl_pipeline_runs(run_id),

    INDEX idx_stg_customers_source_id (source_customer_id)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS stg_products (
    staging_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    etl_run_id BIGINT NULL,
    source_product_id VARCHAR(100),
    product_name VARCHAR(255),
    category VARCHAR(150),
    unit_price VARCHAR(100),
    unit_cost VARCHAR(100),
    stock_quantity VARCHAR(100),
    created_at_source VARCHAR(100),
    source_file VARCHAR(255),
    loaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stg_products_run
        FOREIGN KEY (etl_run_id)
        REFERENCES etl_pipeline_runs(run_id),

    INDEX idx_stg_products_source_id (source_product_id)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS stg_orders (
    staging_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    etl_run_id BIGINT NULL,
    source_order_id VARCHAR(100),
    source_customer_id VARCHAR(100),
    order_date VARCHAR(100),
    order_status VARCHAR(100),
    shipping_country VARCHAR(100),
    shipping_city VARCHAR(100),
    source_file VARCHAR(255),
    loaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stg_orders_run
        FOREIGN KEY (etl_run_id)
        REFERENCES etl_pipeline_runs(run_id),

    INDEX idx_stg_orders_source_id (source_order_id),
    INDEX idx_stg_orders_customer_id (source_customer_id)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS stg_order_items (
    staging_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    etl_run_id BIGINT NULL,
    source_order_item_id VARCHAR(100),
    source_order_id VARCHAR(100),
    source_product_id VARCHAR(100),
    quantity VARCHAR(100),
    unit_price VARCHAR(100),
    discount_amount VARCHAR(100),
    source_file VARCHAR(255),
    loaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stg_order_items_run
        FOREIGN KEY (etl_run_id)
        REFERENCES etl_pipeline_runs(run_id),

    INDEX idx_stg_order_items_item_id (source_order_item_id),
    INDEX idx_stg_order_items_order_id (source_order_id)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS stg_payments (
    staging_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    etl_run_id BIGINT NULL,
    source_payment_id VARCHAR(100),
    source_order_id VARCHAR(100),
    payment_method VARCHAR(100),
    payment_status VARCHAR(100),
    payment_date VARCHAR(100),
    payment_amount VARCHAR(100),
    source_file VARCHAR(255),
    loaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stg_payments_run
        FOREIGN KEY (etl_run_id)
        REFERENCES etl_pipeline_runs(run_id),

    INDEX idx_stg_payments_payment_id (source_payment_id),
    INDEX idx_stg_payments_order_id (source_order_id)
) ENGINE=InnoDB;


-- ============================================================
-- 3. DIMENSION TABLES
-- Surrogate keys are generated by the warehouse.
-- ============================================================

CREATE TABLE IF NOT EXISTS dim_customers (
    customer_key BIGINT AUTO_INCREMENT PRIMARY KEY,
    source_customer_id VARCHAR(100) NOT NULL,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(255),
    phone VARCHAR(50),
    country VARCHAR(100),
    city VARCHAR(100),
    registration_date DATE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    UNIQUE KEY uq_dim_customers_source_id (source_customer_id),
    INDEX idx_dim_customers_country (country),
    INDEX idx_dim_customers_email (email)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS dim_products (
    product_key BIGINT AUTO_INCREMENT PRIMARY KEY,
    source_product_id VARCHAR(100) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    category VARCHAR(150),
    unit_price DECIMAL(12,2) NOT NULL,
    unit_cost DECIMAL(12,2),
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    UNIQUE KEY uq_dim_products_source_id (source_product_id),
    INDEX idx_dim_products_category (category)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS dim_date (
    date_key INT PRIMARY KEY,
    full_date DATE NOT NULL,
    day_number TINYINT NOT NULL,
    day_name VARCHAR(15) NOT NULL,
    day_of_week TINYINT NOT NULL,
    week_number TINYINT NOT NULL,
    month_number TINYINT NOT NULL,
    month_name VARCHAR(15) NOT NULL,
    quarter_number TINYINT NOT NULL,
    year_number SMALLINT NOT NULL,

    UNIQUE KEY uq_dim_date_full_date (full_date),
    INDEX idx_dim_date_year_month (year_number, month_number)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS dim_payment_methods (
    payment_method_key INT AUTO_INCREMENT PRIMARY KEY,
    method_name VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE KEY uq_payment_method_name (method_name)
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS dim_order_statuses (
    order_status_key INT AUTO_INCREMENT PRIMARY KEY,
    status_name VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE KEY uq_order_status_name (status_name)
) ENGINE=InnoDB;


-- ============================================================
-- 4. FACT TABLE: SALES
-- GRAIN: One row per order item.
-- ============================================================

CREATE TABLE IF NOT EXISTS fact_sales (
    sales_key BIGINT AUTO_INCREMENT PRIMARY KEY,

    source_order_item_id VARCHAR(100) NOT NULL,
    source_order_id VARCHAR(100) NOT NULL,

    customer_key BIGINT NOT NULL,
    product_key BIGINT NOT NULL,
    order_date_key INT NOT NULL,
    order_status_key INT NOT NULL,

    quantity INT NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    gross_revenue DECIMAL(14,2) NOT NULL,
    net_revenue DECIMAL(14,2) NOT NULL,
    total_cost DECIMAL(14,2),
    profit DECIMAL(14,2),

    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE KEY uq_fact_sales_source_item (source_order_item_id),

    INDEX idx_fact_sales_order_id (source_order_id),
    INDEX idx_fact_sales_customer (customer_key),
    INDEX idx_fact_sales_product (product_key),
    INDEX idx_fact_sales_date (order_date_key),

    CONSTRAINT fk_fact_sales_customer
        FOREIGN KEY (customer_key)
        REFERENCES dim_customers(customer_key),

    CONSTRAINT fk_fact_sales_product
        FOREIGN KEY (product_key)
        REFERENCES dim_products(product_key),

    CONSTRAINT fk_fact_sales_date
        FOREIGN KEY (order_date_key)
        REFERENCES dim_date(date_key),

    CONSTRAINT fk_fact_sales_status
        FOREIGN KEY (order_status_key)
        REFERENCES dim_order_statuses(order_status_key),

    CONSTRAINT chk_fact_sales_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_fact_sales_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_fact_sales_discount
        CHECK (discount_amount >= 0)
) ENGINE=InnoDB;


-- ============================================================
-- 5. FACT TABLE: PAYMENTS
-- GRAIN: One row per payment transaction.
-- ============================================================

CREATE TABLE IF NOT EXISTS fact_payments (
    payment_key BIGINT AUTO_INCREMENT PRIMARY KEY,

    source_payment_id VARCHAR(100) NOT NULL,
    source_order_id VARCHAR(100) NOT NULL,

    payment_method_key INT NOT NULL,
    payment_date_key INT NOT NULL,

    payment_status VARCHAR(50) NOT NULL,
    payment_amount DECIMAL(14,2) NOT NULL,

    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE KEY uq_fact_payments_source_id (source_payment_id),

    INDEX idx_fact_payments_order_id (source_order_id),
    INDEX idx_fact_payments_date (payment_date_key),
    INDEX idx_fact_payments_method (payment_method_key),

    CONSTRAINT fk_fact_payments_method
        FOREIGN KEY (payment_method_key)
        REFERENCES dim_payment_methods(payment_method_key),

    CONSTRAINT fk_fact_payments_date
        FOREIGN KEY (payment_date_key)
        REFERENCES dim_date(date_key),

    CONSTRAINT chk_fact_payments_amount
        CHECK (payment_amount >= 0)
) ENGINE=InnoDB;


